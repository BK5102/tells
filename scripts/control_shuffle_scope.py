"""Follow-up control: does a model trained on shuffled labels beat random ranking?

Descriptive follow-up, not a pre-registered test. The built-in control
(methodology M37) shuffles training labels within each day. On TabFormer it
beat random ranking, which can mean a leak, or that within-day shuffling keeps
day-level structure (fraud arrives in bursts on particular days). This script
retrains the reference model on labels shuffled three ways and scores the
validation period exactly as the harness does:

- within_day: the built-in control, repeated for comparison
- across_all: labels shuffled over the whole training period (no day structure left)
- across_all_seed1: the same with another seed, to see run-to-run noise

If across_all is consistent with chance while within_day is not, the gap comes
from day-level structure the within-day shuffle preserves, not from a leak.
If across_all also beats random, something leaks and must be found.

Usage:
    uv run python scripts/control_shuffle_scope.py configs/tabformer.yaml docs/analysis/<name>.md
"""

from __future__ import annotations

import sys
from pathlib import Path

import polars as pl
from cleanroom.provenance import file_sha256

from tells.cases import build_cases
from tells.config import load_config
from tells.evaluate import compare_to_reference
from tells.harness import checklist_features, split_data
from tells.models.contestants import make_contestant


def main(config_path: str, out: Path) -> None:
    cfg = load_config(config_path)
    tx = pl.read_parquet(cfg.data)
    tx = tx.join(checklist_features(tx, file_sha256(cfg.data)), on="tx_id", maintain_order="left")
    eval_start = cfg.split.valid.start
    known = set(
        tx.filter((pl.col("ts") < eval_start) & (pl.col("label") == 1))["account_id"].unique()
    )
    parts = split_data(cfg, tx)
    train, valid = parts["train"], parts["valid"]
    budgets = cfg.budgets
    shuffles = {
        "within_day": train.with_columns(
            label=pl.col("label").shuffle(seed=cfg.seed).over(pl.col("ts").dt.date())
        ),
        "across_all": train.with_columns(label=pl.col("label").shuffle(seed=cfg.seed)),
        "across_all_seed1": train.with_columns(label=pl.col("label").shuffle(seed=cfg.seed + 1)),
    }
    lines = [
        f"# Shuffle-scope control on `{cfg.name}` (validation period)",
        "",
        "Descriptive follow-up, not pre-registered. The reference model is retrained on labels "
        "shuffled in different ways and scored on the validation period; each is compared with a "
        "constant score (random ranking) using the account bootstrap (300 resamples). "
        "Differences are in percentage points of first-fraud-day catch. Generated by "
        "`scripts/control_shuffle_scope.py`.",
        "",
        "| Shuffle | Budget | Model on shuffled labels | Random | Difference | 95% interval |",
        "|---|---|---|---|---|---|",
    ]
    for name, shuffled in shuffles.items():
        model = make_contestant(cfg.reference, cfg.model)
        model.fit(shuffled)
        cases = build_cases(
            valid.with_columns(score=model.score(valid)), score_col="score",
            known_positive_accounts=known,
        )  # fmt: skip
        random = cases.with_columns(score=pl.lit(0.0))
        for budget in budgets:
            r = compare_to_reference(
                {"random": random, "model": cases}, "random", "first_day_recall", budget, 300, 0
            )["results"]["model"]
            lines.append(
                f"| {name} | {100 * budget:.1f}% | {100 * r['contestant_value']:.1f}% | "
                f"{100 * r['reference_value']:.1f}% | {100 * r['diff']:+.1f} | "
                f"[{100 * r['ci_low']:+.1f}, {100 * r['ci_high']:+.1f}] |"
            )
        print(f"{name} done", flush=True)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main(sys.argv[1], Path(sys.argv[2]))
