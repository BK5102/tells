"""Descriptive follow-up analysis of a finished run (not pre-registered tests).

Reads only the run's saved case files and results.json, so it is cheap and
cannot change the run. Writes a Markdown file whose numbers are all formatted
by this code. Everything here is labeled descriptive: the only pre-registered
test is the headline in results.json.

Usage:
    uv run python scripts/analyze_test_run.py artifacts/runs/<run_id> docs/analysis/<name>.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import polars as pl
from cleanroom.metrics import budget_selection

from tells.evaluate import compare_to_reference

REF, NEW = "B_checklist_lgbm", "D_checklist_tsfm_ttm"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def pts(x: float) -> str:
    return f"{100 * x:+.1f}"


def main(run_dir: Path, out: Path) -> None:
    s = json.loads((run_dir / "results.json").read_text(encoding="utf-8"))
    budget = s["headline"]["budget"]
    budgets = [float(b) for b in s["contestants"][REF]["cases"]["by_budget"]]
    b = pl.read_parquet(run_dir / f"cases_{REF}.parquet")
    d = pl.read_parquet(run_dir / f"cases_{NEW}.parquet")
    lines = [
        f"# Descriptive analysis of run `{s['run_id']}`",
        "",
        "Not pre-registered. The only formal test is the headline in the run's "
        "`results.json`; everything below explores where contestants differ. "
        f"Comparison: {NEW} (D) against {REF} (B). Generated by "
        "`scripts/analyze_test_run.py` from the run's saved files.",
        "",
        "## 1. Every budget, with 95% intervals (account bootstrap, 300 resamples)",
        "",
        "| Budget | B | D | D minus B | 95% interval |",
        "|---|---|---|---|---|",
    ]
    for bud in budgets:
        r = compare_to_reference({REF: b, NEW: d}, REF, "first_day_recall", bud, 300, 0)
        r = r["results"][NEW]
        mark = " (headline)" if bud == budget else ""
        lines.append(
            f"| {pct(bud)}{mark} | {pct(r['reference_value'])} | {pct(r['contestant_value'])} | "
            f"{pts(r['diff'])} | [{pts(r['ci_low'])}, {pts(r['ci_high'])}] |"
        )
    lines += [
        "",
        "Intervals at budgets other than the headline are uncorrected for multiple comparisons; "
        "treat any that exclude zero as hypotheses for a future sealed test, not findings.",
        "",
        f"## 2. Each day separately, headline budget {pct(budget)}",
        "",
        "| Day | Newly bad accounts | B | D | D minus B |",
        "|---|---|---|---|---|",
    ]
    for day in sorted(b["day"].unique().to_list()):
        bd = b.filter(pl.col("day") == day)
        dd = d.filter(pl.col("day") == day)
        first = bd["is_first_positive"].cast(pl.Float64).to_numpy()
        if first.sum() == 0:
            continue
        sb = budget_selection(bd["score"].to_numpy(), budget)
        sd = budget_selection(dd["score"].to_numpy(), budget)
        rb, rd = (sb * first).sum() / first.sum(), (sd * first).sum() / first.sum()
        lines.append(f"| {day} | {int(first.sum()):,} | {pct(rb)} | {pct(rd)} | {pts(rd - rb)} |")

    days = b["day"].to_numpy()
    first = b["is_first_positive"].to_numpy()
    sb = budget_selection(b["score"].to_numpy(), budget, days)
    sd = budget_selection(d["score"].to_numpy(), budget, days)
    caught_b, caught_d = (sb >= 0.5) & first, (sd >= 0.5) & first
    both = int((caught_b & caught_d).sum())
    only_b = int((caught_b & ~caught_d).sum())
    only_d = int((caught_d & ~caught_b).sum())
    neither = int((first & ~caught_b & ~caught_d).sum())
    lines += [
        "",
        f"## 3. Who catches whom, headline budget {pct(budget)}",
        "",
        "A newly bad account counts as caught when at least half of its review slot is used "
        "(ties share slots).",
        "",
        "| | Count |",
        "|---|---|",
        f"| Caught by both | {both:,} |",
        f"| Caught only by B | {only_b:,} |",
        f"| Caught only by D | {only_d:,} |",
        f"| Caught by neither | {neither:,} |",
        "",
        "If D only added catches, 'caught only by B' would be near zero. Similar counts in both "
        "rows mean the TSFM columns reshuffle the queue rather than add to it.",
    ]
    if "history_len" in b.columns:
        pass
    agree = np.corrcoef(b["score"].to_numpy(), d["score"].to_numpy())[0, 1]
    lines += ["", f"Score correlation between B and D across all cases: {agree:.3f}."]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main(Path(sys.argv[1]), Path(sys.argv[2]))
